"""
app/routers/predictions.py
============================
GET /api/v1/predictions/{vehicle_id}

This is THE integration point with your existing ML model API.

FLOW:
  1. Pull the last 50 telemetry readings for the vehicle from PostgreSQL
  2. Convert them into the feature format your ML model expects
  3. Call your ML model API
  4. If it succeeds: save the prediction, run alert rules, return it
  5. If it fails/times out: use a simple fallback formula so the
     dashboard never shows a blank screen
"""

from fastapi import APIRouter, HTTPException
from datetime import datetime
from app.models.schemas import PredictionOut
from app.db.database import get_pool
from app.services.ml_client import build_ml_features, call_ml_api, fallback_prediction
from app.services.alert_service import run_alert_rules_for_prediction

router = APIRouter()


@router.get("/predictions/{vehicle_id}", response_model=PredictionOut)
async def get_prediction(vehicle_id: str):
    """
    Returns ML-predicted Remaining Useful Life (RUL) and SoH forecast
    for one vehicle, calling your trained ML model API.
    """
    pool = await get_pool()

    # Step 1 — fetch recent telemetry history
    async with pool.acquire() as conn:
        rows = await conn.fetch("""
            SELECT state_of_health, state_of_charge, cycle_count,
                   current_amps, temperature_cell, charge_rate_kw, is_charging,
                   internal_resistance, action_voltage, action_current,
                   dT_dt, dV_dt, thermal_stress_index, aging_indicator,
                   charging_efficiency, charging_time, cycle_degradation, balancing_time
            FROM telemetry_events
            WHERE vehicle_id = $1
            ORDER BY recorded_at DESC
            LIMIT 50
        """, vehicle_id)

    if not rows:
        raise HTTPException(
            status_code=404,
            detail=f"No telemetry data for {vehicle_id} yet — send telemetry first"
        )

    history = [dict(r) for r in rows]
    print("====== HISTORY ======")
    print(history[0])
    print("=====================")

    # Step 2 — build the feature vector your ML model expects
    features = build_ml_features(vehicle_id, history)

    # Step 3 — call your ML model API
    result = await call_ml_api(features)

    used_fallback = False
    if result is None:
        # ML API unavailable — use simple physics-based estimate instead
        result = fallback_prediction(features)
        used_fallback = True

    # Step 4 — cache the prediction in PostgreSQL
    async with pool.acquire() as conn:
        await conn.execute("""
            INSERT INTO ml_predictions (
                vehicle_id, rul_days, soh_forecast_30d, soh_forecast_90d,
                degradation_rate, confidence_score
            ) VALUES ($1, $2, $3, $4, $5, $6)
        """,
            vehicle_id, result.rul_days, result.soh_forecast_30d,
            result.soh_forecast_90d, result.degradation_rate, result.confidence_score,
        )

    # Step 5 — run alert rules based on the prediction (e.g. "RUL < 30 days")
    await run_alert_rules_for_prediction(vehicle_id, result)

    return PredictionOut(
        vehicle_id=vehicle_id,
        rul_days=result.rul_days,
        rul_months=round(result.rul_days / 30, 1),
        soh_forecast_30d=result.soh_forecast_30d,
        soh_forecast_90d=result.soh_forecast_90d,
        degradation_rate=result.degradation_rate,
        confidence_score=result.confidence_score,
        predicted_soh=result.predicted_soh,
        status=result.status,
        prediction_note=(
            "Fallback estimate — ML model unavailable" if used_fallback
            else "Generated by ML model"
        ),
        computed_at=datetime.utcnow(),
    )


@router.get("/predictions/{vehicle_id}/history")
async def get_prediction_history(vehicle_id: str, limit: int = 20):
    """Returns past predictions for a vehicle — useful for trend charts."""
    pool = await get_pool()
    async with pool.acquire() as conn:
        rows = await conn.fetch("""
            SELECT predicted_at, rul_days, soh_forecast_30d,
                   soh_forecast_90d, degradation_rate, confidence_score
            FROM ml_predictions
            WHERE vehicle_id = $1
            ORDER BY predicted_at DESC
            LIMIT $2
        """, vehicle_id, limit)

    return [dict(r) for r in rows]
